"""Tests for PyiWriter (PEP 484 .pyi type stub writer)."""

from __future__ import annotations

import ast
import sys
import textwrap
from pathlib import Path

import pytest

from headerkit._cli import main
from headerkit.ir import (
    Array,
    Constant,
    CType,
    Enum,
    EnumValue,
    Field,
    Function,
    FunctionPointer,
    Header,
    Parameter,
    Pointer,
    Struct,
    Typedef,
    Variable,
)
from headerkit.writers import get_writer, list_writers
from headerkit.writers.pyi import PyiWriter


class TestPyiWriter:
    """Unit and integration tests for PyiWriter."""

    def test_pyi_writer_registered(self) -> None:
        """Verify 'pyi' is registered in the writer registry."""
        writers = list_writers()
        assert "pyi" in writers
        writer = get_writer("pyi")
        assert isinstance(writer, PyiWriter)
        assert writer.name == "pyi"
        assert writer.default_output_pattern == "{dir}/{stem}.pyi"

    def test_functions_primitives_and_strings(self) -> None:
        """Verify primitive C types, void, bool, and char* map to exact PEP 484 types."""
        header = Header(
            path="math_api.h",
            declarations=[
                Function(
                    name="add",
                    return_type=CType("int"),
                    parameters=[
                        Parameter("a", CType("int")),
                        Parameter("b", CType("int32_t")),
                    ],
                ),
                Function(
                    name="scale",
                    return_type=CType("double"),
                    parameters=[
                        Parameter("val", CType("float")),
                        Parameter("enabled", CType("bool")),
                    ],
                ),
                Function(
                    name="greet",
                    return_type=Pointer(CType("char", ["const"])),
                    parameters=[
                        Parameter("name", Pointer(CType("char", ["const"]))),
                    ],
                ),
                Function(
                    name="reset",
                    return_type=CType("void"),
                    parameters=[],
                ),
            ],
        )
        writer = PyiWriter()
        actual = writer.write(header)
        expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            def add(a: int, b: int) -> int: ...

            def scale(val: float, enabled: bool) -> float: ...

            def greet(name: bytes | str) -> bytes: ...

            def reset() -> None: ...
        """)
        assert actual == expected
        ast.parse(actual)

    def test_structs_enums_pointers_and_callbacks(self) -> None:
        """Verify structs, enums, opaque handles, void*, and function pointers."""
        header = Header(
            path="types.h",
            declarations=[
                Constant(name="API_VERSION", value=3),
                Enum(
                    name="Status",
                    values=[
                        EnumValue("STATUS_OK", 0),
                        EnumValue("STATUS_ERR", -1),
                    ],
                ),
                Struct(
                    name="Point",
                    fields=[
                        Field("x", CType("double")),
                        Field("y", CType("double")),
                    ],
                ),
                Struct(
                    name="OpaqueHandle",
                    fields=[],
                ),
                Typedef(
                    name="Callback",
                    underlying_type=Pointer(
                        FunctionPointer(
                            return_type=CType("int"),
                            parameters=[
                                Parameter("code", CType("int")),
                                Parameter("ctx", Pointer(CType("void"))),
                            ],
                        )
                    ),
                ),
                Variable(name="global_count", type=CType("size_t")),
                Function(
                    name="move_point",
                    return_type=Pointer(CType("Point")),
                    parameters=[
                        Parameter("pt", Pointer(CType("Point"))),
                        Parameter("cb", CType("Callback")),
                        Parameter("raw", Pointer(CType("void"))),
                        Parameter("coords", Array(CType("double"), 2)),
                    ],
                    doc="Move a point and invoke callback.",
                ),
            ],
        )
        writer = PyiWriter()
        actual = writer.write(header)
        expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            from collections.abc import Callable
            import enum
            from typing import Any

            API_VERSION: int = 3

            class Status(enum.IntEnum):
                STATUS_OK: int = 0
                STATUS_ERR: int = -1

            class Point:
                x: float
                y: float

            class OpaqueHandle:
                ...

            Callback = Callable[[int, Any], int]

            global_count: int

            def move_point(pt: Point, cb: Callback, raw: Any, coords: list[float]) -> Point:
                \"\"\"Move a point and invoke callback.\"\"\"
                ...
        """)
        assert actual == expected
        ast.parse(actual)

    def test_exclude_patterns_negative_control(self) -> None:
        """Verify exclude_patterns omits matching declarations while preserving non-matching ones."""
        header = Header(
            path="api.h",
            declarations=[
                Function("public_fn", CType("int"), [Parameter("x", CType("int"))]),
                Function("_internal_helper", CType("void"), []),
            ],
        )
        writer = PyiWriter(exclude_patterns=[r"^_internal"])
        actual = writer.write(header)
        expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            def public_fn(x: int) -> int: ...
        """)
        assert actual == expected

    def test_cli_end_to_end_pyi_generation(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        """Verify CLI 'headerkit mylib.h -b tree-sitter -w pyi -o pyi:mylib.pyi' works end-to-end."""
        header_file = tmp_path / "mylib.h"
        header_file.write_text(
            textwrap.dedent("""\
                typedef struct Vec2 {
                    double x;
                    double y;
                } Vec2;
                int compute_norm(Vec2* v, const char* label);
            """),
            encoding="utf-8",
        )
        out_pyi = tmp_path / "mylib.pyi"
        monkeypatch.setattr(
            sys,
            "argv",
            [
                "headerkit",
                "--no-config",
                "--no-cache",
                "-b",
                "tree-sitter",
                "-w",
                "pyi",
                "-o",
                f"pyi:{out_pyi}",
                str(header_file),
            ],
        )
        exit_code = main()
        assert exit_code == 0
        actual = out_pyi.read_text(encoding="utf-8")
        expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            class Vec2:
                x: float
                y: float

            def compute_norm(v: Vec2, label: bytes | str) -> int: ...
        """)
        assert actual == expected
        ast.parse(actual)

    def test_edge_cases_elaborated_bool_invalid_expr_and_doc_escaping(self) -> None:
        """Verify elaborated struct tags, bool constants, invalid C expressions, void(void) fnptr, and doc escaping."""
        header = Header(
            path="edge_cases.h",
            declarations=[
                Constant(name="IS_ENABLED", value=True, doc='Flag with trailing quote"'),
                Constant(name="BAD_EXPR", value="((unsigned int)1U << 4)"),
                Enum(
                    name="Flags",
                    values=[
                        EnumValue("FLAG_VALID", "1 << 2"),
                        EnumValue("FLAG_INVALID", "(int)0x1"),
                    ],
                ),
                Struct(
                    name="char",
                    fields=[Field("code", CType("int", is_elaborated=False))],
                ),
                Typedef(
                    name="VoidCallback",
                    underlying_type=Pointer(
                        FunctionPointer(
                            return_type=CType("void", is_elaborated=False),
                            parameters=[Parameter(None, CType("void", is_elaborated=False))],
                        )
                    ),
                    doc=r"Callback with C:\path\to\file.",
                ),
                Variable(
                    name="unnamed_type_var",
                    type=CType("   ", is_elaborated=False),
                    doc="Variable with fallback Any.",
                ),
                Function(
                    name="use_elaborated_char",
                    return_type=Pointer(CType("char", is_elaborated=True)),
                    parameters=[Parameter("c", CType("char", is_elaborated=True))],
                ),
            ],
        )
        writer = PyiWriter()
        actual = writer.write(header)
        expected = textwrap.dedent('''\
            # Auto-generated by headerkit - do not edit

            from collections.abc import Callable
            import enum
            from typing import Any

            IS_ENABLED: bool = True
            """Flag with trailing quote\\""""

            BAD_EXPR: int = ...

            class Flags(enum.IntEnum):
                FLAG_VALID: int = 1 << 2
                FLAG_INVALID: int = ...

            class char:
                code: int

            VoidCallback = Callable[[], None]
            """Callback with C:\\\\path\\\\to\\\\file."""

            unnamed_type_var: Any
            """Variable with fallback Any."""

            def use_elaborated_char(c: char) -> char: ...
        ''')
        assert actual == expected
        ast.parse(actual)

    def test_user_declared_type_shadowing_scalar_name_not_coerced(self) -> None:
        """Verify elaborated struct tags vs bare scalar/typedef spellings follow C namespace rules."""
        header = Header(
            path="shadow.h",
            declarations=[
                Struct(
                    name="int8_t",
                    fields=[Field("x", CType("int", is_elaborated=False))],
                ),
                Struct(
                    name="Gauge",
                    fields=[Field("val", CType("double", is_elaborated=False))],
                ),
                Typedef(
                    name="Gauge",
                    underlying_type=CType("unsigned char", is_elaborated=False),
                ),
                Function(
                    name="consume_shadowed",
                    return_type=CType("int8_t", is_elaborated=False),
                    parameters=[
                        Parameter("s_rec", CType("int8_t", is_elaborated=True)),
                        Parameter("s_ptr", Pointer(CType("int8_t", is_elaborated=True))),
                        Parameter("s_int", CType("int8_t", is_elaborated=False)),
                        Parameter("g_rec", CType("Gauge", is_elaborated=True)),
                        Parameter("g_val", CType("Gauge", is_elaborated=False)),
                    ],
                ),
            ],
        )
        writer = PyiWriter()
        actual = writer.write(header)
        expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            class int8_t:
                x: int

            class Gauge:
                val: float

            def consume_shadowed(s_rec: int8_t, s_ptr: int8_t, s_int: int, g_rec: Gauge, g_val: int) -> int: ...
        """)
        assert actual == expected
        ast.parse(actual)
