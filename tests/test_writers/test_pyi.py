    def test_type_overrides_and_ctypes_pointer_normalization(self) -> None:
        """Verify type_overrides['pyi'] and ctypes._Pointer[T] normalization."""
        header = Header(
            path="overrides.h",
            declarations=[
                Struct(
                    name="Box",
                    fields=[
                        Field("flag", CType("uint8_t"), type_overrides={"pyi": "bool"}),
                        Field("ptr", Pointer(CType("int")), type_overrides={"pyi": "ctypes.pointer[ctypes.c_int]"}),
                    ],
                ),
                Function(
                    name="check_box",
                    return_type=CType("uint8_t"),
                    parameters=[
                        Parameter("enabled", CType("uint8_t"), type_overrides={"pyi": "bool"}),
                        Parameter("raw_ptr", Pointer(CType("int"))),
                    ],
                    type_overrides={"pyi": "bool"},
                ),
            ],
        )
        writer = PyiWriter(pointer_style="ctypes", module_var="CDEF")
        actual = writer.write(header)
        expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            import ctypes

            class Box:
                flag: bool
                ptr: ctypes._Pointer[ctypes.c_int]

            def check_box(enabled: bool, raw_ptr: ctypes._Pointer[int]) -> bool: ...

            CDEF: str
        """)
        assert actual == expected
        ast.parse(actual)

    def test_cffi_mode_emits_ffi_and_final_lib_class(self) -> None:
        """Verify mode='cffi' emits ffi: cffi.FFI, @final class _Lib, and lib: _Lib."""
        header = Header(
            path="nng.h",
            declarations=[
                Constant("NNG_FLAG_ALLOC", 1),
                Enum("nng_pipe_ev", [EnumValue("NNG_PIPE_EV_ADD", 0), EnumValue("NNG_PIPE_EV_REM", 1)]),
                Struct("nng_socket", [Field("id", CType("uint32_t"))]),
                Function(
                    "nng_close",
                    CType("int"),
                    [Parameter("sock", CType("nng_socket"))],
                    doc="Close a socket.",
                ),
            ],
        )
        writer = PyiWriter(mode="cffi")
        actual = writer.write(header)
        expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            import cffi
            import enum
            from typing import final

            class nng_pipe_ev(enum.IntEnum):
                NNG_PIPE_EV_ADD = 0
                NNG_PIPE_EV_REM = 1

            class nng_socket:
                id: int

            ffi: cffi.FFI

            @final
            class _Lib:
                NNG_FLAG_ALLOC: int = 1
                NNG_PIPE_EV_ADD: int = 0
                NNG_PIPE_EV_REM: int = 1
                def nng_close(self, sock: nng_socket) -> int:
                    \"\"\"Close a socket.\"\"\"
                    ...

            lib: _Lib
        """)
        assert actual == expected
        ast.parse(actual)

    def test_cffi_mode_pointer_parameters_and_narrow_returns(self) -> None:
        """Verify mode='cffi' widens struct/union/char pointer params with cffi.FFI.CData while keeping returns/fields/value-params narrow."""
        header = Header(
            path="device.h",
            declarations=[
                Enum("DeviceStatus", [EnumValue("DEV_OK", 0), EnumValue("DEV_ERR", 1)]),
                Struct(
                    "DeviceConfig",
                    [
                        Field("timeout_ms", CType("int")),
                        Field("label", Pointer(CType("char", ["const"]))),
                        Field("next_cfg", Pointer(CType("DeviceConfig"))),
                    ],
                ),
                Struct("OpaqueHandle", []),
                Struct(
                    "PayloadUnion",
                    [
                        Field("raw", CType("uint64_t")),
                        Field("ptr", Pointer(CType("void"))),
                    ],
                    is_union=True,
                ),
                Typedef("DeviceConfigAlias", CType("DeviceConfig", is_elaborated=True)),
                Typedef("ChainedConfigAlias", CType("DeviceConfigAlias")),
                Typedef("DurationMs", CType("int32_t")),
                Function(
                    "device_init",
                    CType("DeviceStatus"),
                    [
                        Parameter("cfg_ptr", Pointer(CType("DeviceConfig", ["const"]))),
                        Parameter("inline_struct_ptr", Pointer(Struct("DeviceConfig", []))),
                        Parameter("alias_ptr", Pointer(CType("ChainedConfigAlias"))),
                        Parameter("opaque_ptr", Pointer(CType("OpaqueHandle"))),
                        Parameter("union_ptr", Pointer(CType("PayloadUnion", is_elaborated=True))),
                        Parameter("name", Pointer(CType("char", ["const"]))),
                    ],
                ),
                Function(
                    "device_process_by_value",
                    Pointer(CType("DeviceConfig")),
                    [
                        Parameter("cfg_val", CType("DeviceConfig")),
                        Parameter("dur", CType("DurationMs")),
                        Parameter("status_ptr", Pointer(CType("DeviceStatus", is_elaborated=True))),
                    ],
                ),
                Function(
                    "device_get_name",
                    Pointer(CType("char", ["const"])),
                    [Parameter("handle", Pointer(CType("OpaqueHandle")))],
                ),
            ],
        )
        writer = PyiWriter(
            mode="cffi",
            extern_python=["void on_device_event(DeviceConfig *cfg, const char *reason, DeviceConfig by_val);"],
        )
        actual = writer.write(header)
        expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            import cffi
            import enum
            from typing import Any, final

            class DeviceStatus(enum.IntEnum):
                DEV_OK = 0
                DEV_ERR = 1

            class DeviceConfig:
                timeout_ms: int
                label: bytes
                next_cfg: DeviceConfig

            class OpaqueHandle:
                ...

            class PayloadUnion:
                raw: int
                ptr: Any

            DeviceConfigAlias = DeviceConfig

            ChainedConfigAlias = DeviceConfigAlias

            DurationMs = int

            ffi: cffi.FFI

            @final
            class _Lib:
                DEV_OK: int = 0
                DEV_ERR: int = 1
                def device_init(self, cfg_ptr: DeviceConfig | cffi.FFI.CData, inline_struct_ptr: DeviceConfig | cffi.FFI.CData, alias_ptr: ChainedConfigAlias | cffi.FFI.CData, opaque_ptr: OpaqueHandle | cffi.FFI.CData, union_ptr: PayloadUnion | cffi.FFI.CData, name: bytes | str | cffi.FFI.CData) -> DeviceStatus: ...
                def device_process_by_value(self, cfg_val: DeviceConfig, dur: DurationMs, status_ptr: DeviceStatus) -> DeviceConfig: ...
                def device_get_name(self, handle: OpaqueHandle | cffi.FFI.CData) -> bytes: ...
                def on_device_event(self, cfg: DeviceConfig | cffi.FFI.CData, reason: bytes | str | cffi.FFI.CData, by_val: DeviceConfig) -> None: ...

            lib: _Lib
        """)
        assert actual == expected
        ast.parse(actual)

        # Negative control: pep484 mode on the same Header must NOT emit cffi.FFI.CData or import cffi
        pep484_writer = PyiWriter(mode="pep484")
        pep484_actual = pep484_writer.write(header)
        pep484_expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            import enum
            from typing import Any

            class DeviceStatus(enum.IntEnum):
                DEV_OK = 0
                DEV_ERR = 1

            class DeviceConfig:
                timeout_ms: int
                label: bytes
                next_cfg: DeviceConfig

            class OpaqueHandle:
                ...

            class PayloadUnion:
                raw: int
                ptr: Any

            DeviceConfigAlias = DeviceConfig

            ChainedConfigAlias = DeviceConfigAlias

            DurationMs = int

            def device_init(cfg_ptr: DeviceConfig, inline_struct_ptr: DeviceConfig, alias_ptr: ChainedConfigAlias, opaque_ptr: OpaqueHandle, union_ptr: PayloadUnion, name: bytes | str) -> DeviceStatus: ...

            def device_process_by_value(cfg_val: DeviceConfig, dur: DurationMs, status_ptr: DeviceStatus) -> DeviceConfig: ...

            def device_get_name(handle: OpaqueHandle) -> bytes: ...
        """)
        assert pep484_actual == pep484_expected
        ast.parse(pep484_actual)

        # Negative control: pointer_style='ctypes' preserves ctypes._Pointer[T] and bytes | str
        ctypes_writer = PyiWriter(pointer_style="ctypes")
        ctypes_actual = ctypes_writer.write(header)
        ctypes_expected = textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            import ctypes
            import enum

            class DeviceStatus(enum.IntEnum):
                DEV_OK = 0
                DEV_ERR = 1

            class DeviceConfig:
                timeout_ms: int
                label: bytes
                next_cfg: ctypes._Pointer[DeviceConfig]

            class OpaqueHandle:
                ...

            class PayloadUnion:
                raw: int
                ptr: ctypes.c_void_p

            DeviceConfigAlias = DeviceConfig

            ChainedConfigAlias = DeviceConfigAlias

            DurationMs = int

            def device_init(cfg_ptr: ctypes._Pointer[DeviceConfig], inline_struct_ptr: ctypes._Pointer[DeviceConfig], alias_ptr: ctypes._Pointer[ChainedConfigAlias], opaque_ptr: ctypes._Pointer[OpaqueHandle], union_ptr: ctypes._Pointer[PayloadUnion], name: bytes | str) -> DeviceStatus: ...

            def device_process_by_value(cfg_val: DeviceConfig, dur: DurationMs, status_ptr: ctypes._Pointer[DeviceStatus]) -> ctypes._Pointer[DeviceConfig]: ...

            def device_get_name(handle: ctypes._Pointer[OpaqueHandle]) -> bytes: ...
        """)
        assert ctypes_actual == ctypes_expected
        ast.parse(ctypes_actual)

        # Verify direct _format_type sets _needs_cffi = True whenever cffi.FFI.CData is emitted
        fresh_writer = PyiWriter(mode="cffi")
        assert fresh_writer._needs_cffi is False
        assert (
            fresh_writer._format_type(Pointer(Struct("DeviceConfig", [])), is_param=True)
            == "DeviceConfig | cffi.FFI.CData"
        )
        assert fresh_writer._needs_cffi is True

    def test_invalid_mode_or_pointer_style_raises(self) -> None:
        with pytest.raises(ValueError, match="Unsupported PyiWriter mode"):
            PyiWriter(mode="invalid")  # type: ignore[arg-type]
        with pytest.raises(ValueError, match="Unsupported pointer_style"):
            PyiWriter(pointer_style="invalid")  # type: ignore[arg-type]
