                        Parameter("s_rec", CType("int8_t", is_elaborated=True)),
                        Parameter("s_ptr", Pointer(CType("int8_t", is_elaborated=True))),
                        Parameter("s_int", CType("int8_t", is_elaborated=False)),
                        Parameter("g_rec", CType("Gauge", is_elaborated=True)),
