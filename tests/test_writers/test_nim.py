    def test_anonymous_enum_collision_disambiguation(self) -> None:
        """Anonymous enum constants colliding with proc names raise SymbolCollisionError unless resolved."""
        from headerkit.hooks import HookRegistry, Priority

        e1 = Enum(
            name="",
            namespace="juce::StandardApplicationCommandIDs",
            values=[EnumValue(name="cut", value=100), EnumValue(name="copy", value=101)],
        )
        e2 = Enum(
            name="",
            values=[EnumValue(name="reset", value=200)],
        )
        f_cut = Function(name="cut", return_type=CType("void"))
        f_copy = Function(name="copy", return_type=CType("void"))
        f_reset = Function(name="reset", return_type=CType("void"))
        h = Header(path="test.h", declarations=[e1, e2, f_cut, f_copy, f_reset])

        with pytest.raises(SymbolCollisionError) as excinfo:
            write_nim(h, header_path="test.h")
        assert "copy" in str(excinfo.value) or "cut" in str(excinfo.value)

        saved = HookRegistry.snapshot()
        try:

            def resolver(collided, _target, *, context=None, **_):
                mapping = {}
                for sym in collided:
                    if sym.kind == "enumerator":
                        if sym.namespace:
                            last_ns = sym.namespace.split("::")[-1]
                            mapping[sym] = f"{last_ns}_{sym.name}"
                        else:
                            mapping[sym] = f"{sym.name}_val"
                    else:
                        mapping[sym] = sym.name
                return mapping

            HookRegistry.register_global("resolve_collision", resolver, priority=Priority.PROJECT, writer="nim")
            code = write_nim(h, header_path="test.h")
            assert "StandardApplicationCommandIDs_cut* = 100" in code
            assert "StandardApplicationCommandIDs_copy* = 101" in code
            assert "reset_val* = 200" in code
        finally:
            HookRegistry.restore(saved)


