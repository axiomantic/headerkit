"""Tests for the TypeScript WebAssembly (.d.ts) writer."""

from __future__ import annotations

import textwrap

from headerkit.ir import (
    Array,
    CType,
    Function,
    FunctionPointer,
    Header,
    Parameter,
    Pointer,
    Reference,
    Struct,
    Typedef,
)
from headerkit.writers import get_writer, get_writer_info, list_writer_options, list_writers
from headerkit.writers.base import ScaffoldOptions, WriterOption
from headerkit.writers.ts_wasm import TsWasmWriter, write_ts_wasm


class TestTsWasmWriter:
    """Tests for TsWasmWriter registration, type mapping, JSDoc, and overrides."""

    def test_ts_wasm_writer_registration(self) -> None:
        assert "ts_wasm" in list_writers()
        writer = get_writer("ts_wasm")
        assert isinstance(writer, TsWasmWriter)
        assert writer.name == "ts_wasm"
        assert writer.default_extension == ".d.ts"
        assert writer.default_output_pattern == "{dir}/{stem}.d.ts"
        assert writer.supported_layouts == ("file",)
        assert writer.hash_comment_format() == "// {line}"
        ts_wasm_info = next(item for item in get_writer_info() if item["name"] == "ts_wasm")
        assert ts_wasm_info == {
            "name": "ts_wasm",
            "description": "TypeScript WebAssembly (.d.ts) declarations",
            "is_default": False,
        }
        assert list_writer_options("ts_wasm") == (
            WriterOption(
                name="interface_name",
                description="Name of the exported WebAssembly.Exports TypeScript interface",
                default="WasmExports",
                type=str,
            ),
            WriterOption(
                name="include_memory",
                description="Include readonly memory: WebAssembly.Memory in the interface",
                default=True,
                type=bool,
            ),
        )

    def test_scalar_and_pointer_type_mappings(self) -> None:
        header = Header(
            path="codec.h",
            declarations=[
                Typedef(name="timestamp_t", underlying_type=CType("uint64_t")),
                Typedef(name="handle_t", underlying_type=CType("uint32_t")),
                Struct(name="ctx_s"),
                Function(
                    name="codec_init",
                    return_type=Pointer(CType("struct ctx_s")),
                    parameters=[
                        Parameter("flags", CType("uint32_t")),
                        Parameter("scale", CType("double")),
                    ],
                ),
                Function(
                    name="codec_decode",
                    return_type=CType("int32_t"),
                    parameters=[
                        Parameter("ctx", Pointer(CType("struct ctx_s"))),
                        Parameter("input_buf", Pointer(CType("uint8_t", qualifiers=["const"]))),
                        Parameter("input_len", CType("size_t")),
                        Parameter("pts", CType("int64_t")),
                        Parameter("dts", CType("timestamp_t")),
                        Parameter("handle", CType("handle_t")),
                    ],
                ),
                Function(
                    name="codec_set_callback",
                    return_type=CType("void"),
                    parameters=[
                        Parameter(
                            "cb",
                            FunctionPointer(
                                return_type=CType("int"),
                                parameters=[Parameter("code", CType("int"))],
                            ),
                        ),
                        Parameter("lut", Array(element_type=CType("int16_t"), size=16)),
                        Parameter("ref_val", Reference(target=CType("int"))),
                    ],
                ),
            ],
        )
        out = write_ts_wasm(header)
        assert out == textwrap.dedent("""\
            // Generated by headerkit

            export interface WasmExports extends WebAssembly.Exports {
              readonly memory: WebAssembly.Memory;
              codec_init(flags: number, scale: number): number;
              codec_decode(ctx: number, input_buf: number, input_len: number, pts: bigint, dts: bigint, handle: number): number;
              codec_set_callback(cb: number, lut: number, ref_val: number): void;
            }
        """)

    def test_jsdoc_deprecation_and_type_overrides(self) -> None:
        header = Header(
            path="api.h",
            declarations=[
                Function(
                    name="compute_crc",
                    return_type=CType("uint32_t"),
                    parameters=[
                        Parameter("data", Pointer(CType("uint8_t")), type_overrides={"ts_wasm": "WasmPtr"}),
                        Parameter("default", CType("size_t")),
                    ],
                    doc="Compute CRC32 checksum over buffer.",
                    type_overrides={"ts": "Crc32Value"},
                ),
                Function(
                    name="legacy_reset",
                    return_type=CType("void"),
                    parameters=[Parameter(None, CType("unsigned long long"))],
                    doc="Reset state machine.\nUse v2 reset instead.",
                    is_deprecated=True,
                ),
            ],
        )
        out = write_ts_wasm(header, interface_name="ApiWasmExports", include_memory=False)
        assert out == textwrap.dedent("""\
            // Generated by headerkit

            export interface ApiWasmExports extends WebAssembly.Exports {
              /** Compute CRC32 checksum over buffer. */
              compute_crc(data: WasmPtr, default_: number): Crc32Value;
              /**
               * Reset state machine.
               * Use v2 reset instead.
               * @deprecated
               */
              legacy_reset(arg0: bigint): void;
            }
        """)
        assert "readonly memory" not in out

    def test_write_layout_file_mode_with_options(self) -> None:
        header = Header(
            path="math.h",
            declarations=[
                Function(
                    name="add_i64",
                    return_type=CType("int64_t"),
                    parameters=[
                        Parameter("a", CType("int64_t")),
                        Parameter("b", CType("int64_t")),
                    ],
                ),
            ],
        )
        opts = ScaffoldOptions(
            package_name="math_wasm",
            target_language="ts_wasm",
            layout="file",
            options={"interface_name": "MathExports", "include_memory": True},
        )
        layout = TsWasmWriter().write_layout(header, opts)
        assert len(layout.files) == 1
        assert layout.files[0].path == "math_wasm.d.ts"
        assert layout.files[0].content == textwrap.dedent("""\
            // Generated by headerkit

            export interface MathExports extends WebAssembly.Exports {
              readonly memory: WebAssembly.Memory;
              add_i64(a: bigint, b: bigint): bigint;
            }
        """)
