class TestDiffWriterAuditRemediations:
    """Tests for [CRIT-4.1], [HIGH-4.3], [HIGH-4.4], and [HIGH-4.5] in DiffWriter."""

    def test_typedef_replaced_by_incompatible_struct_is_flagged_in_abi_mode(self) -> None:
        baseline = Header(
            path="v1.h",
            declarations=[
                Typedef("my_handle_t", CType("int32_t")),
                Function("process_handle", CType("void"), [Parameter("h", CType("my_handle_t"))]),
            ],
        )
        target = Header(
            path="v2.h",
            declarations=[
                Struct(
                    "my_handle_t",
                    fields=[Field("hi", CType("int64_t")), Field("lo", CType("int64_t"))],
                    is_typedef=True,
                ),
                Function("process_handle", CType("void"), [Parameter("h", CType("my_handle_t"))]),
            ],
        )
        report = diff_headers(baseline, target, abi_mode=True)
        breaking_kinds = [(e.kind, e.name) for e in report.entries if e.severity == "breaking"]
        assert breaking_kinds == [
            ("typedef_removed", "my_handle_t"),
            ("function_signature_changed", "process_handle"),
        ]

    def test_enum_underlying_width_and_const_mismatch_detected_in_c_abi_mode(self) -> None:
        baseline = Header(
            path="v1.h",
            declarations=[
                Enum("packet_kind", [EnumValue("PKT_A", 0)], underlying_type="uint8_t"),
                Typedef("packet_kind_t", CType("enum packet_kind")),
                Function(
                    "send_packet",
                    CType("packet_kind_t"),
                    [Parameter("buf", Pointer(CType("char", ["const"])))],
                ),
            ],
        )
        target = Header(
            path="v2.h",
            declarations=[
                Enum("packet_kind", [EnumValue("PKT_A", 0)], underlying_type="uint64_t"),
                Typedef("packet_kind_t", CType("enum packet_kind")),
                Function(
                    "send_packet",
                    CType("packet_kind_t"),
                    [Parameter("buf", Pointer(CType("char")))],
                ),
            ],
        )
        report = diff_headers(baseline, target, abi_mode=True)
        assert report.entries == [
            DiffEntry(
                kind="enum_underlying_type_changed",
                severity="breaking",
                name="packet_kind",
                detail="enum underlying type changed from 'uint8_t' to 'uint64_t'",
                baseline="uint8_t",
                target="uint64_t",
            ),
            DiffEntry(
                kind="typedef_changed",
                severity="breaking",
                name="packet_kind_t",
                detail="underlying type changed from 'enum packet_kind' to 'enum packet_kind'",
                baseline="enum packet_kind",
                target="enum packet_kind",
            ),
            DiffEntry(
                kind="function_signature_changed",
                severity="breaking",
                name="send_packet",
                detail="return type changed from 'packet_kind_t' to 'packet_kind_t'",
                baseline="packet_kind_t",
                target="packet_kind_t",
            ),
            DiffEntry(
                kind="function_signature_changed",
                severity="breaking",
                name="send_packet",
                detail="parameter 0 type changed from 'const char*' to 'char*'",
                baseline="const char*",
                target="char*",
            ),
        ]

    def test_nim_comparison_reports_genuinely_removed_unreferenced_typedef(self) -> None:
        baseline = Header(
            path="api.h",
            declarations=[
                Typedef("inlined_ms_t", CType("int32_t")),
                Typedef("removed_public_alias_t", CType("int64_t")),
                Function("sleep_ms", CType("void"), [Parameter("d", CType("inlined_ms_t"))]),
            ],
        )
        raw_target = Header(
            path="nim_api.h",
            declarations=[
                Function("sleep_ms", CType("void"), [Parameter("d_p0", CType("NI32"))]),
                Function("NimMain", CType("void"), []),
            ],
        )
        target = clean_nim_c_unit(raw_target)
        report = diff_headers(baseline, target, abi_mode=True)
        assert [e.name for e in report.entries if e.kind == "typedef_removed"] == ["removed_public_alias_t"]
        assert [e.name for e in report.entries if e.kind == "function_signature_changed"] == []


