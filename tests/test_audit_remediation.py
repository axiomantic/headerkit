class TestLayer2CacheTransitiveHeaderInvalidation:
    """Tests for [CRIT-5.1]: Layer-2 output cache invalidation when transitive included_headers change."""

    def test_transitive_included_header_change_invalidates_layer2_output_cache(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        (tmp_path / ".git").mkdir()
        store_dir = tmp_path / ".headerkit"
        umbrella_h = tmp_path / "umbrella.h"
        inner_h = tmp_path / "inner.h"

        umbrella_h.write_text('#include "inner.h"\n', encoding="utf-8")
        inner_h.write_text("int compute_val(int x);\n", encoding="utf-8")

        current_decls = [Function("compute_val", CType("int"), [Parameter("x", CType("int"))])]
        parse_count = 0

        class TransitiveMockBackend:
            name = "libclang"

            def parse(
                self,
                code: str,
                path: str,
                include_dirs: object = None,
                extra_args: object = None,
                **kw: object,
            ) -> Header:
                nonlocal parse_count
                parse_count += 1
                return Header(
                    path=str(umbrella_h),
                    declarations=list(current_decls),
                    included_headers={str(inner_h)},
                )

        monkeypatch.setattr("headerkit._generate.get_backend", lambda _name: TransitiveMockBackend())
        monkeypatch.setattr("headerkit._generate.is_backend_available", lambda _name: True)

        # 1. Initial generation populates Layer-1 IR and Layer-2 output caches
        out1 = generate(
            header_path=umbrella_h,
            writer_name="pyi",
            backend_name="libclang",
            store_dir=store_dir,
        )
        assert parse_count == 1
        assert out1 == textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            def compute_val(x: int) -> int: ...
        """)

        # 2. Unchanged second call hits both caches without re-parsing
        out2 = generate(
            header_path=umbrella_h,
            writer_name="pyi",
            backend_name="libclang",
            store_dir=store_dir,
        )
        assert parse_count == 1
        assert out2 == out1

        # 3. Modify transitive included header WITHOUT touching umbrella.h
        inner_h.write_text("double compute_val(double x, int flags);\n", encoding="utf-8")
        current_decls = [
            Function(
                "compute_val",
                CType("double"),
                [Parameter("x", CType("double")), Parameter("flags", CType("int"))],
            )
        ]

        # Layer-1 invalidates AND Layer-2 must NOT serve stale cached output!
        out3 = generate(
            header_path=umbrella_h,
            writer_name="pyi",
            backend_name="libclang",
            store_dir=store_dir,
        )
        assert parse_count == 2
        assert out3 == textwrap.dedent("""\
            # Auto-generated by headerkit - do not edit

            def compute_val(x: float, flags: int) -> float: ...
        """)

        # 4. Subsequent call serves the updated Layer-2 output from cache
        out4 = generate(
            header_path=umbrella_h,
            writer_name="pyi",
            backend_name="libclang",
            store_dir=store_dir,
        )
        assert parse_count == 2
        assert out4 == out3

        # 5. Negative control: if inner_h is modified again while libclang is unavailable,
        # _try_output_cache_fallback must refuse to serve stale output and raise LibclangUnavailableError
        inner_h.write_text("void compute_val(void);\n", encoding="utf-8")
        monkeypatch.setattr("headerkit._generate.is_backend_available", lambda _name: False)
        with pytest.raises(LibclangUnavailableError):
            generate(
                header_path=umbrella_h,
                writer_name="pyi",
                backend_name="libclang",
                store_dir=store_dir,
            )


