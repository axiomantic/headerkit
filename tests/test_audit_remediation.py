class TestLibclangPathNormalizationAndTransformsAndConfig:
    """Tests for [HIGH-5.1], [HIGH-5.3], [HIGH-2.3], [MED-4.5], [MED-2.1], [MED-2.2], [MED-5.2], [LOW-2.1]."""

    def test_normalize_path_collapses_parent_traversal_in_project_prefix_check(self) -> None:
        assert normalize_path("/repo/include/lvgl/../../vendor/lvgl/lv_color.h") == "/repo/vendor/lvgl/lv_color.h"
        assert (
            _matches_project_prefix(
                "/repo/include/lvgl/../../vendor/lvgl/lv_color.h",
                ("/repo/include",),
            )
            is False
        )
        assert (
            _matches_project_prefix(
                "/repo/include/lvgl/../sub/lv_color.h",
                ("/repo/include",),
            )
            is True
        )

    def test_nim_cleanup_filters_tySequence_and_ts_wasm_maps_nim_scalars(self) -> None:
        raw_unit = Header(
            path="nim_out.h",
            declarations=[
                Struct("tySequence__a1b2c3", fields=[Field("len", CType("NI"))]),
                Struct("tySequence__a1b2c3_Content", fields=[Field("cap", CType("NI"))]),
                Typedef("tySequence__a1b2c3", CType("struct tySequence__a1b2c3")),
                Function(
                    "wasm_compute",
                    CType("NI64"),
                    [
                        Parameter("count_p0", CType("NI32")),
                        Parameter("scale_p1", CType("NF64")),
                        Parameter("uval_p2", CType("NU64")),
                    ],
                ),
            ],
        )
        dts_raw = write_ts_wasm(raw_unit)
        assert dts_raw == textwrap.dedent("""\
            // Generated by headerkit

            export interface WasmExports extends WebAssembly.Exports {
              readonly memory: WebAssembly.Memory;
              wasm_compute(count_p0: number, scale_p1: number, uval_p2: bigint): bigint;
            }
        """)

        cleaned = raw_unit >> NimCleanupTransform()
        assert [d.name for d in cleaned.declarations] == ["wasm_compute"]

    def test_filter_by_symbol_cascades_into_anonymous_inner_structs_and_nested_records(self) -> None:
        anon = Struct(
            name=None,
            is_union=True,
            fields=[
                Field("secret", Pointer(CType("_priv_t"))),
                Field("public_val", CType("int")),
            ],
        )
        nested = Struct(
            name="InnerRec",
            fields=[
                Field("hidden_ref", CType("_priv_t")),
                Field("visible_id", CType("int")),
            ],
        )
        outer = Struct(
            name="PublicContainer",
            fields=[
                Field("", CType("union (unnamed)"), anonymous_struct=anon),
                Field("ok", CType("int")),
            ],
            nested_records=[nested],
        )
        unit = Header(
            path="cascade.h",
            declarations=[
                Typedef("_priv_t", CType("int")),
                outer,
            ],
        )
        filtered = unit >> FilterBySymbol(exclude=["_*"], cascade_excluded_types=True)
        assert len(filtered.declarations) == 1
        res_struct = filtered.declarations[0]
        assert isinstance(res_struct, Struct)
        assert res_struct.fields[0].anonymous_struct is not None
        assert [f.name for f in res_struct.fields[0].anonymous_struct.fields] == ["public_val"]
        assert [f.name for f in res_struct.nested_records[0].fields] == ["visible_id"]

    def test_filter_unexported_symbols_matches_cpp_mangled_name(self) -> None:
        cpp_fn = Function(
            name="createEngine",
            return_type=CType("void"),
            parameters=[Parameter("flags", CType("int"))],
            mangled_name="_ZN5audio12createEngineEi",
        )
        unexported_fn = Function(
            name="deadHelper",
            return_type=CType("void"),
            parameters=[],
            mangled_name="_ZN5audio10deadHelperEv",
        )
        unit = Header(path="engine.hpp", declarations=[cpp_fn, unexported_fn])
        filtered = unit >> FilterUnexportedSymbolsTransform(exported_symbols={"__ZN5audio12createEngineEi"})
        assert [d.name for d in filtered.declarations] == ["createEngine"]

    def test_nim_jsondoc_fingerprint_includes_nim_source_sha256(self, tmp_path: Path) -> None:
        nim_src = tmp_path / "mod.nim"
        nim_src.write_text("proc hello*(): cint = 1\n", encoding="utf-8")
        enricher = NimJsonDocEnricher(nim_source_path=nim_src)
        fp1 = enricher.cache_fingerprint()
        assert fp1["config"]["nim_source_sha256"] is not None

        nim_src.write_text("proc hello*(): cint = 2\n", encoding="utf-8")
        fp2 = enricher.cache_fingerprint()
        assert fp2["config"]["nim_source_sha256"] != fp1["config"]["nim_source_sha256"]

    def test_config_writer_options_alias_embedded_target_and_ts_wasm_extension(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        (tmp_path / ".git").mkdir()
        hdr = tmp_path / "periph.h"
        hdr.write_text("int read_sensor(void);\n", encoding="utf-8")
        cfg_path = tmp_path / "headerkit.toml"
        cfg_path.write_text(
            textwrap.dedent("""\
                [writer_options.ts_wasm]
                interface_name = "SensorWasm"

                [[targets]]
                name = "nim_embedded"
                writer = "nim"
                headers = ["periph.h"]
                target = "embedded"

                [[targets]]
                name = "wasm_dts"
                writer = "ts_wasm"
                headers = ["periph.h"]
            """),
            encoding="utf-8",
        )
